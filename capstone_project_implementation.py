def train_bigram_model(sentences):

    unigram_counts = Counter()
    bigram_counts = Counter()

    for sentence in sentences:

        words = sentence.lower().split()

        previous = "<START>"

        for word in words:

            unigram_counts[previous] += 1

            bigram_counts[(previous, word)] += 1

            previous = word

        unigram_counts[previous] += 1

    return unigram_counts, bigram_counts

def calculate_bigram_score(
    sentence,
    unigram_counts,
    bigram_counts
):

    words = sentence.lower().split()

    previous = "<START>"

    log_probability = 0

    for word in words:

        bigram_count = bigram_counts[
            (previous, word)
        ]

        unigram_count = unigram_counts[
            previous
        ]

        # Laplace smoothing
        probability = (
            bigram_count + 1
        ) / (
            unigram_count + len(unigram_counts)
        )

        log_probability += math.log(
            probability
        )

        previous = word

    return log_probability

