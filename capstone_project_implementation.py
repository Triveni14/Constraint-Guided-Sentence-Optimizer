def beam_search(words, beam_width=3):

    beams = [
        ([], words.copy(), 0)
    ]

    for _ in range(len(words)):

        new_beams = []

        for current_sentence, remaining_words, old_score in beams:

            for word in remaining_words:

                new_sentence = (
                    current_sentence + [word]
                )

                new_remaining = (
                    remaining_words.copy()
                )

                new_remaining.remove(word)

