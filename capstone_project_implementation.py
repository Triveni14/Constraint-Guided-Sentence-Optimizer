def beam_search(words, beam_width=3):

    # Each beam contains:
    # (current_sentence, remaining_words, score)

    beams = [
        ([], words.copy(), 0)
    ]

    for _ in range(len(words)):

        new_beams = []

        for current_sentence, remaining_words, old_score in beams:

            for word in remaining_words:

                # Create new sentence
                new_sentence = current_sentence + [word]

                # Remove selected word
                new_remaining = remaining_words.copy()
                new_remaining.remove(word)

                # Convert to text
                sentence_text = " ".join(new_sentence)

                # Calculate perplexity
                score = get_perplexity(sentence_text)

                # Store candidate
                new_beams.append(
                    (
                        new_sentence,
                        new_remaining,
                        score
                    )
                )

        # Sort by perplexity
        # Lower perplexity = better
        new_beams.sort(
            key=lambda x: x[2]
        )

        # Keep only best beam_width candidates
        beams = new_beams[:beam_width]

    # Select best complete sentence
    best_sentence, remaining, best_score = min(
        beams,
        key=lambda x: x[2]
    )

    return " ".join(best_sentence), best_score

