import random
import math


def simulated_annealing(
    words,
    initial_temperature=100,
    cooling_rate=0.95,
    max_iterations=100
):

    current = words.copy()

    current_sentence = " ".join(current)

    current_score = get_perplexity(
        current_sentence
    )

    best = current.copy()
    best_score = current_score

    temperature = initial_temperature

    for iteration in range(max_iterations):

        # Generate neighboring solution
        neighbor = generate_neighbor(current)

        neighbor_sentence = " ".join(neighbor)

        neighbor_score = get_perplexity(
            neighbor_sentence
        )

        # Difference
        delta = neighbor_score - current_score

        # Accept if better
        if delta < 0:

            current = neighbor
            current_score = neighbor_score

        else:

            # Probability of accepting worse solution
            probability = math.exp(
                -delta / max(temperature, 1e-8)
            )

            if random.random() < probability:

                current = neighbor
                current_score = neighbor_score

        # Update best solution
        if current_score < best_score:

            best = current.copy()
            best_score = current_score

        # Cool down
        temperature *= cooling_rate

    return " ".join(best), best_score

