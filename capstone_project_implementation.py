import random


def generate_neighbor(words):
    """
    Generate a neighboring sentence
    by swapping two words.
    """

    new_words = words.copy()

    i, j = random.sample(range(len(new_words)), 2)

    new_words[i], new_words[j] = new_words[j], new_words[i]

    return new_words


def local_search(words, max_iterations=100):

    # Initial solution
    current = words.copy()

    current_sentence = " ".join(current)

